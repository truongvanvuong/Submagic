# Invert for S2T mapping
S2T_DICT: dict[str, str] = {v: k for k, v in T2S_DICT.items()}

# Set of characters that exist ONLY in Traditional Chinese
TRAD_ONLY_CHARS = set(T2S_DICT.keys()) - set(T2S_DICT.values())

# Set of characters that exist ONLY in Simplified Chinese
SIMP_ONLY_CHARS = set(T2S_DICT.values()) - set(T2S_DICT.keys())


def convert_t2s(text: str) -> str:
    """
    Convert Traditional Chinese to Simplified Chinese (OpenCC t2s fallback).
    Translates character by character or uses OpenCC if installed.
    """
    if not text:
        return ""
    if _OPENCC_T2S is not None:
        try:
            return _OPENCC_T2S.convert(text)
        except Exception:
            pass
    return "".join(T2S_DICT.get(ch, ch) for ch in text)


def convert_s2t(text: str) -> str:
    """
    Convert Simplified Chinese to Traditional Chinese (OpenCC s2t fallback).
    Translates character by character or uses OpenCC if installed.
    """
    if not text:
        return ""
    if _OPENCC_S2T is not None:
        try:
            return _OPENCC_S2T.convert(text)
        except Exception:
            pass
    return "".join(S2T_DICT.get(ch, ch) for ch in text)


def count_trad_simp_characters(text: str) -> Tuple[int, int]:
    """
    Count the number of distinct characters that are exclusive to Traditional
    and exclusive to Simplified Chinese within the provided text line.
    Returns: (trad_count, simp_count)
    """
    if not text:
        return 0, 0
    trad_count = sum(1 for ch in text if ch in TRAD_ONLY_CHARS)
    simp_count = sum(1 for ch in text if ch in SIMP_ONLY_CHARS)
    return trad_count, simp_count


def is_mixed_cjk_script(text: str, min_chars: int = 1) -> bool:
    """
    Determine if a line substantially mixes Traditional and Simplified Chinese glyphs.
    Returns True if both Traditional-only and Simplified-only glyphs exist.
    """
    trad_cnt, simp_cnt = count_trad_simp_characters(text)
    return trad_cnt >= min_chars and simp_cnt >= min_chars
